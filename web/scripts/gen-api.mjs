// Generate src/api/schema.ts from the server's OpenAPI document (docs/api/openapi.json).
// Run with `npm run api` after `make api` regenerates the document. CI fails if the output differs.
import fs from "node:fs";
import ts from "typescript";
import openapiTS, { astToString } from "openapi-typescript";

const source = new URL("../../docs/api/openapi.json", import.meta.url);
const target = new URL("../src/api/schema.ts", import.meta.url);

// The recursive `Json` schema becomes a standalone recursive type: TypeScript cannot resolve a
// self-reference through `components["schemas"]["Json"]`.
const JSON_TYPE =
  "/** Any JSON value (the server's recursive `Json` schema). */\n" +
  "export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };\n";

const ast = await openapiTS(source, {
  inject: JSON_TYPE,
  transform(schema, metadata) {
    if (metadata.path === "#/components/schemas/Json") {
      return ts.factory.createTypeReferenceNode("JsonValue");
    }
    return undefined;
  },
});

const header = "// Generated by `npm run api` from docs/api/openapi.json. Do not edit by hand.\n\n";
fs.writeFileSync(target, header + astToString(ast));
